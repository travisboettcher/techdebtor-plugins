import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest

from conftest import assistant_text, human, write_jsonl
from retro_mine import (YamlLiteError, category_counts, ledger_report, load_ledger, load_run_records,
                        parse_yaml_lite)

NOW = datetime(2026, 11, 21, 12, 0, tzinfo=timezone.utc)
SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "retro_mine.py"

RECORD = """\
schema: 1
date: 2026-11-21
task: "One-line description: with a colon"
repo: name-of-repo            # basename of the git root
outcome: merged               # merged | reworked | abandoned | in-progress
stages:                       # what ran, in order
  - plan
  - implement
findings:                     # anything a later stage had to catch
  - stage: review
    category: generated-file-hand-edit   # kebab-case
    severity: major
    detail: "Edited the generated file #2 instead of its source."
    caught_by: reviewer
    fixed: true
  - stage: human
    category: scope-creep
    severity: minor
    detail: 'It''s too big'
    caught_by: human
    fixed: false
notes: "Free text, optional."
"""

LEDGER = """\
schema: 1
rules:
  - id: generated-file-hand-edit-1
    category: generated-file-hand-edit
    rung: hook
    scope: project
    location: ".claude/settings.json (PreToolUse hook)"
    summary: "Block edits to files whose first line is '# Generated by'."
    added: 2026-11-10
    baseline: 3
    history:
      - date: 2026-11-15
        occurrences_since: 0
        verdict: working
  - id: old-rule-1
    category: never-seen
    rung: instruction
    scope: project
    location: CLAUDE.md
    summary: Something old.
    added: 2026-06-01
    baseline: 2
    history: []
"""


def test_parse_run_record_shape():
    rec = parse_yaml_lite(RECORD)
    assert rec["schema"] == 1
    assert rec["date"] == "2026-11-21"
    assert rec["task"] == "One-line description: with a colon"
    assert rec["repo"] == "name-of-repo"
    assert rec["stages"] == ["plan", "implement"]
    assert len(rec["findings"]) == 2
    f0, f1 = rec["findings"]
    assert f0["category"] == "generated-file-hand-edit"
    assert f0["detail"] == "Edited the generated file #2 instead of its source."
    assert f0["fixed"] is True
    assert f1["detail"] == "It's too big"
    assert f1["fixed"] is False
    assert rec["notes"] == "Free text, optional."


def test_parse_ledger_shape():
    led = parse_yaml_lite(LEDGER)
    r0, r1 = led["rules"]
    assert r0["baseline"] == 3
    assert r0["history"] == [{"date": "2026-11-15", "occurrences_since": 0, "verdict": "working"}]
    assert r1["history"] == []
    assert r1["summary"] == "Something old."


def test_parse_block_scalar_and_empty_values():
    doc = parse_yaml_lite("notes: |\n  line one\n  line two\nfindings: []\nother:\n")
    assert doc["notes"] == "line one\nline two\n"
    assert doc["findings"] == []
    assert doc["other"] is None


def test_parse_folded_scalar_and_flow_list():
    doc = parse_yaml_lite("notes: >\n  a\n  b\nstages: [plan, test]\n")
    assert doc["notes"] == "a b\n"
    assert doc["stages"] == ["plan", "test"]


def test_parse_errors_raise():
    with pytest.raises(YamlLiteError):
        parse_yaml_lite("a: 1\n   b: 2\n  - c\n")


def _write(root, name, text):
    p = root / ".claude" / "runs" / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    return p


def test_load_run_records_reports_bad_files(tmp_path):
    _write(tmp_path, "2026-11-21-good.yml", RECORD)
    _write(tmp_path, "2026-11-20-bad.yml", "schema: 1\n  oops: [\n token=ghp_" + "A" * 36 + "\n")
    _write(tmp_path, "framework-proposals.md", "# not a record")
    recs, errors = load_run_records(tmp_path)
    assert len(recs) == 1 and recs[0]["_file"].endswith("2026-11-21-good.yml")
    assert len(errors) == 1
    assert "ghp_" not in json.dumps(errors)  # raw text is redacted
    assert errors[0]["raw"]


def test_run_record_strings_are_redacted(tmp_path):
    _write(tmp_path, "2026-11-21-x.yml", RECORD.replace("Free text, optional.", "see 192.168.1.5"))
    recs, _ = load_run_records(tmp_path)
    assert "192.168.1.5" not in json.dumps(recs)


def _records():
    mk = lambda date, *cats: {"date": date, "findings": [
        {"category": c, "severity": s} for c, s in cats]}
    return [
        mk("2026-11-05", ("generated-file-hand-edit", "major")),
        mk("2026-11-10", ("generated-file-hand-edit", "minor")),  # same day as rule: before it
        mk("2026-11-12", ("generated-file-hand-edit", "critical"), ("scope-creep", "minor")),
        mk("2026-11-18", ("scope-creep", "minor")),
        mk("2026-09-01", ("scope-creep", "major")),               # outside window
        {"date": "2026-11-19", "findings": None},
    ]


def test_category_counts_within_window():
    since = datetime(2026, 11, 1, tzinfo=timezone.utc)
    counts = category_counts(_records(), since)
    assert counts["generated-file-hand-edit"]["count"] == 3
    assert counts["generated-file-hand-edit"]["by_severity"] == {"major": 1, "minor": 1, "critical": 1}
    assert counts["generated-file-hand-edit"]["last_seen"] == "2026-11-12"
    assert counts["scope-creep"]["count"] == 2


def test_ledger_occurrences_since_added(tmp_path):
    p = tmp_path / "rules-ledger.yml"
    p.write_text(LEDGER)
    ledger = load_ledger(p, "project")
    rep = ledger_report(ledger, _records(), NOW)
    r0, r1 = rep["rules"]
    assert r0["id"] == "generated-file-hand-edit-1"
    assert r0["occurrences_since"] == 1            # strictly after 2026-11-10
    assert r0["last_occurrence"] == "2026-11-12"
    assert r0["records_since_added"] == 3          # run activity since the rule (11-12, 11-18, 11-19)
    assert r0["days_since_added"] == 11
    assert r0["last_verdict"] == "working"
    assert r1["occurrences_since"] == 0
    assert r1["last_occurrence"] is None
    assert r1["days_since_added"] > 90


def test_missing_ledger_is_none(tmp_path):
    assert load_ledger(tmp_path / "nope.yml", "user") is None


def test_cli_end_to_end(tmp_path):
    root = tmp_path / "repo"
    _write(root, "2026-11-20-a.yml", RECORD.replace("2026-11-21", "2026-11-20"))
    (root / ".claude" / "rules-ledger.yml").write_text(LEDGER)
    t = write_jsonl(tmp_path / "t" / "s.jsonl", [
        human("go", "2026-11-20T10:00:00Z"), assistant_text("done", "2026-11-20T10:00:01Z"),
        human("no, that's wrong", "2026-11-20T10:00:02Z")])
    out = subprocess.run([sys.executable, str(SCRIPT), "--root", str(root), "--since", "2026-11-01",
                          "--transcripts", str(t), "--user-ledger", str(tmp_path / "none.yml")],
                         capture_output=True, text=True, check=True)
    data = json.loads(out.stdout)
    assert data["schema"] == 1
    assert data["signal_counts"] == {"correction": 1}
    assert data["category_counts"]["generated-file-hand-edit"]["count"] == 1
    assert data["ledgers"]["project"]["rules"][0]["occurrences_since"] == 1
    assert data["ledgers"]["user"] is None
    assert data["run_records"]["count_in_window"] == 1


# --- quoting and escapes ----------------------------------------------------

def test_escaped_quotes_and_hash_inside_strings():
    doc = parse_yaml_lite('a: "Reviewer flagged \\"no # check\\" path"\n'
                          "b: 'It''s fine # really'\n"
                          'c: "back\\\\slash" # trailing comment\n'
                          "d: [\"x, \\\"y\\\"\", 'z''s']\n")
    assert doc["a"] == 'Reviewer flagged "no # check" path'
    assert doc["b"] == "It's fine # really"
    assert doc["c"] == "back\\slash"
    assert doc["d"] == ['x, "y"', "z's"]


def test_escaped_quotes_in_run_record_file(tmp_path):
    text = RECORD.replace('detail: "Edited the generated file #2 instead of its source."',
                          'detail: "Reviewer flagged \\"no # check\\" path"')
    text = text.replace("detail: 'It''s too big'", "detail: 'It''s fine # really'")
    _write(tmp_path, "2026-11-21-q.yml", text)
    recs, errors = load_run_records(tmp_path)
    assert errors == []
    f0, f1 = recs[0]["findings"]
    assert f0["detail"] == 'Reviewer flagged "no # check" path'
    assert f1["detail"] == "It's fine # really"


