"""Write textutil/_charmap.py: characters that slugify spells out instead of dropping."""

from pathlib import Path

CHARMAP = {"&": "and", "@": "at", "%": "percent"}

lines = ["# Generated by scripts/gen_charmap.py; do not edit by hand.", "", "CHARMAP = {"]
lines += [f"    {key!r}: {value!r}," for key, value in sorted(CHARMAP.items())]
lines += ["}", ""]
Path(__file__).resolve().parent.parent.joinpath("textutil", "_charmap.py").write_text("\n".join(lines))
